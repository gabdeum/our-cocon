"""Writes packages/calendar/title-font.ts: Nunito Black's advance widths and kerning for the
characters calendar titles use, so `titleWidth` measures a title the same way on web and iPhone
(spec 034 FR-007). Run again only if the font or the title words change:

    pip install fonttools
    python3 scripts/title-font.py
"""
import glob
import json
import os

from fontTools.ttLib import TTFont

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..')
FONT = glob.glob(os.path.join(ROOT, 'node_modules/.pnpm/@expo-google-fonts+nunito@*/node_modules/@expo-google-fonts/nunito/900Black/Nunito_900Black.ttf'))[0]
OUT = os.path.join(ROOT, 'packages/calendar/title-font.ts')

# Month and weekday names (words.en.ts), digits and the separators: ", ", ". ", " – ".
CHARS = sorted(set('JanuaryFebruaryMarchAprilMayJuneJulyAugustSeptemberOctoberNovemberDecember'
                   'SundayMondayTuesdayWednesdayThursdayFridaySaturday0123456789,.– '
                   'Coming up'))

font = TTFont(FONT)
upm = font['head'].unitsPerEm
cmap = font.getBestCmap()
hmtx = font['hmtx']
glyph = {c: cmap[ord(c)] for c in CHARS}
advance = {c: hmtx[glyph[c]][0] * 1000 // upm for c in CHARS}

kern = {}
for lookup in font['GPOS'].table.LookupList.Lookup:
    for sub in lookup.SubTable:
        if lookup.LookupType == 9:
            sub = sub.ExtSubTable
        if sub.LookupType != 2:
            continue
        cov = set(sub.Coverage.glyphs)
        for a in CHARS:
            if glyph[a] not in cov:
                continue
            for b in CHARS:
                if (a + b) in kern:
                    continue
                value = None
                if sub.Format == 1:
                    pairs = sub.PairSet[sub.Coverage.glyphs.index(glyph[a])].PairValueRecord
                    value = next((p.Value1 for p in pairs if p.SecondGlyph == glyph[b]), None)
                else:
                    record = sub.Class1Record[sub.ClassDef1.classDefs.get(glyph[a], 0)]
                    value = record.Class2Record[sub.ClassDef2.classDefs.get(glyph[b], 0)].Value1
                x = getattr(value, 'XAdvance', 0) if value else 0
                if x:
                    kern[a + b] = x * 1000 // upm

with open(OUT, 'w') as out:
    out.write('// Generated by scripts/title-font.py from Nunito_900Black.ttf. Do not edit.\n')
    out.write('// Units per 1000 em: multiply by the font size / 1000 for pixels.\n\n')
    out.write('export const ADVANCE: Readonly<Record<string, number>> = ' + json.dumps(advance, ensure_ascii=False) + ';\n\n')
    out.write('export const KERN: Readonly<Record<string, number>> = ' + json.dumps(dict(sorted(kern.items())), ensure_ascii=False) + ';\n')
print(f'{len(advance)} characters, {len(kern)} kerning pairs → {os.path.relpath(OUT, ROOT)}')
