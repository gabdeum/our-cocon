// `pnpm catalog`: validates data/catalog/ingredients.json (spec 031 FR-001, SC-002) and, if it
// changed, writes a new `*_catalog_data.sql` migration that loads it. `pnpm catalog --check`
// changes nothing and fails if the data is invalid or no migration matches it (CI runs it).
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { CatalogFile, matchNames } from '../packages/schemas/catalog';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
export const catalogPath = join(root, 'data/catalog/ingredients.json');
export const migrationsDir = join(root, 'supabase/migrations');
const DATA_MIGRATION = /^(\d{14})_catalog_data\.sql$/;

/** The SQL that loads this catalog. Deterministic, so `--check` can compare it with the last one. */
export function catalogSql(json: unknown): string {
  const file = CatalogFile.parse(json);
  const rows = [...file.ingredients]
    .sort((a, b) => a.key.localeCompare(b.key))
    .map((e) =>
      JSON.stringify({
        key: e.key,
        names: e.names,
        synonyms: e.synonyms ?? {},
        aisle: e.aisle,
        density_g_per_ml: e.density_g_per_ml ?? null,
        size_small_g: e.sizes?.small ?? null,
        size_medium_g: e.sizes?.medium ?? null,
        size_large_g: e.sizes?.large ?? null,
        default_size: e.default_size ?? null,
        noun_singular: e.nouns?.singular ?? null,
        noun_plural: e.nouns?.plural ?? null,
        whole_only: e.whole_only,
        diet: e.diet,
        packs: (['us', 'eu'] as const).flatMap((profile) =>
          (e.packs?.[profile] ?? []).map((p, position) => ({ profile, position, ...p })),
        ),
        match: matchNames(e),
      }),
    );
  const body = `{"version": ${file.version}, "ingredients": [\n${rows.join(',\n')}\n]}`;
  if (body.includes('$catalog$')) throw new Error('The catalog may not contain "$catalog$"');
  return [
    '-- Generated by `pnpm catalog` from data/catalog/ingredients.json (spec 031). Do not edit:',
    '-- change the JSON and run `pnpm catalog`, which writes a new migration.',
    `select public._load_catalog($catalog$${body}$catalog$::jsonb);`,
    '',
  ].join('\n');
}

function latestDataMigration(): { file: string; sql: string } | null {
  const files = readdirSync(migrationsDir).filter((f) => DATA_MIGRATION.test(f)).sort();
  const file = files.at(-1);
  return file ? { file, sql: readFileSync(join(migrationsDir, file), 'utf8') } : null;
}

/** A version later than every migration, so the new data loads last. */
function nextVersion(): string {
  const now = new Date().toISOString().replace(/\D/g, '').slice(0, 14);
  const last = readdirSync(migrationsDir).map((f) => f.slice(0, 14)).filter((v) => /^\d{14}$/.test(v)).sort().at(-1);
  return last && last >= now ? String(BigInt(last) + 1n) : now;
}

export function run(check: boolean): { ok: boolean; message: string } {
  let sql: string;
  try {
    sql = catalogSql(JSON.parse(readFileSync(catalogPath, 'utf8')));
  } catch (error) {
    return { ok: false, message: `data/catalog/ingredients.json is invalid:\n${error instanceof Error ? error.message : String(error)}` };
  }
  const latest = latestDataMigration();
  if (latest?.sql === sql) return { ok: true, message: '' };
  if (check) {
    return { ok: false, message: 'No migration loads the current data/catalog/ingredients.json.\nRun `pnpm catalog` and commit the new migration.' };
  }
  const file = `${nextVersion()}_catalog_data.sql`;
  writeFileSync(join(migrationsDir, file), sql);
  return { ok: true, message: `Wrote supabase/migrations/${file}` };
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const { ok, message } = run(process.argv.includes('--check'));
  if (message) (ok ? process.stdout : process.stderr).write(`${message}\n`);
  process.exit(ok ? 0 : 1);
}
