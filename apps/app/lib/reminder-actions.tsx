const r = strings.reminders;

/** What every reminders screen needs: the family, me, the home time zone and today in it, and the clock. */
export function useReminderContext() {
  const { state, client, tracker } = useSession();
  const familyId = state.status === 'ready' ? state.family.id : null;
  const settings = useQuery({ queryKey: calendarSettingsKey(familyId ?? ''), queryFn: () => loadCalendarSettings(client), enabled: familyId !== null });
  // The family's home time zone, or the device's until one is set (as the event sheet does).
  const tz = settings.data?.homeTimeZone ?? Intl.DateTimeFormat().resolvedOptions().timeZone;
  const { prefs } = useCalendarDisplay();
  // Spec 059 (L149): each person's quiet hours and clock, for the sheet's "Notifies {name} at …".
  const quiet = useQuery({ queryKey: ['member_calendar_settings', 'family', familyId ?? ''], queryFn: () => loadFamilyQuietHours(client), enabled: familyId !== null });
  const myMemberId = state.status === 'ready' ? (state.members.find((m) => m.user_id === state.userId)?.id ?? state.me.id) : null;
  return {
    state,
    client,
    tracker,
    familyId,
    myMemberId,
    userId: state.status === 'ready' ? state.userId : null,
    members: state.status === 'ready' ? state.members : [],
    tz,
    today: todayIn(tz),
    use24h: prefs.use24h,
    weekStartsOn: prefs.weekStartsOn,
    quietHours: quiet.data,
  };
}

export type ReminderContext = ReturnType<typeof useReminderContext>;

/** Closes the new or edit sheet; opened straight from a link there's nothing to go back to: the Reminders screen. */
// Cast: the typed routes file (.expo/types) is generated by `expo start`.
export const closeReminderSheet = () => (router.canGoBack() ? router.back() : router.replace('/reminders' as Href));

// FR-003: "Mine" or "Everyone's", remembered per person on this device (as the calendar's filter).
const mineKey = (userId: string) => `cocon.reminders.mine.${userId}`;

export async function readMine(storage: ChoiceStorage, userId: string): Promise<boolean> {
  try {
    return (await storage.getItem(mineKey(userId))) === 'mine';
  } catch {
    return false;
  }
}

/** Best effort: if the device refuses, the choice still works, it just isn't remembered. */
export async function writeMine(storage: ChoiceStorage, userId: string, mine: boolean): Promise<void> {
  try {
    await storage.setItem(mineKey(userId), mine ? 'mine' : 'everyone');
  } catch {
    // Not kept, nothing to say.
  }
}

/** The filter for this person; null until it's read, so the screen loads one list, not two. Everyone's at first. */
export function useReminderMine(userId: string | null, storage: ChoiceStorage = deviceStorage) {
  const [stored, setStored] = useState<{ userId: string; mine: boolean } | null>(null);
  useEffect(() => {
    if (!userId) return;
    let live = true;
    void readMine(storage, userId).then((mine) => live && setStored({ userId, mine }));
    return () => {
      live = false;
    };
  }, [storage, userId]);
  const mine = stored && stored.userId === userId ? stored.mine : null;
  const set = useCallback(
    (next: boolean) => {
      if (!userId) return;
      setStored({ userId, mine: next });
      void writeMine(storage, userId, next);
    },
    [storage, userId],
  );
  return [mine, set] as const;
}

/** A row ticked on this screen: shown struck through until the screen is left (FR-001). */
export interface TickedRow {
  row: PlacedReminder;
  /** For Undo; null while it's saving. */
  done: CompletedReminder | null;
}

/**
 * FR-007: ticks, snoozes and deletes, shown at once and saved; a failed save puts the row back
 * and says "Couldn't save. Try again." (056). Ticked rows stay until the screen loses focus.
 */
export function useReminderActions(ctx: Pick<ReminderContext, 'client' | 'tracker' | 'familyId' | 'tz'>) {
  const { client, tracker, familyId, tz } = ctx;
  const queryClient = useQueryClient();
  const toast = useToast();
  const [ticked, setTicked] = useState<ReadonlyMap<string, TickedRow>>(new Map());
  const [hidden, setHidden] = useState<ReadonlySet<string>>(new Set());

  const refresh = useCallback(() => void queryClient.invalidateQueries({ queryKey: ['reminders', familyId ?? ''] }), [queryClient, familyId]);
  const failed = useCallback(() => toast.show({ text: r.saveFailed, tone: 'warn' }), [toast]);
  const withTick = (id: string, entry: TickedRow | null) =>
    setTicked((prev) => {
      const next = new Map(prev);
      if (entry) next.set(id, entry);
      else next.delete(id);
      return next;
    });
  const withHidden = (id: string, on: boolean) =>
    setHidden((prev) => {
      const next = new Set(prev);
      if (on) next.add(id);
      else next.delete(id);
      return next;
    });

  // Leaving the screen lets the ticked rows go (the next ones have moved up meanwhile).
  useFocusEffect(
    useCallback(
      () => () => {
        setTicked(new Map());
        setHidden(new Set());
      },
      [],
    ),
  );

  /** FR-004 Done. Returns the result for the drawer's confirmation, or null when it didn't save. */
  const tick = async (row: PlacedReminder, source: ReminderActionSource): Promise<CompletedReminder | null> => {
    withTick(row.id, { row, done: null });
    try {
      const done = await completeReminder(client, row.id, tz);
      if (done) {
        withTick(row.id, { row, done });
        tracker.track('reminder_completed', { repeating: done.repeating, late_days: Math.min(row.late_days, 3660), source });
      }
      refresh();
      // Someone else ticked it first: it's done either way.
      return done;
    } catch {
      withTick(row.id, null);
      failed();
      return null;
    }
  };

  /**
   * Undo of a tick: one from this screen, or one done earlier today (spec 058: `done`, from
   * `loadRemindersDoneToday`), which is reopened if nobody moved the reminder since.
   */
  const untick = async (id: string, done?: DoneReminder): Promise<boolean> => {
    const entry = ticked.get(id);
    if (!entry?.done) {
      if (!done?.undo) return false;
      withHidden(`${id}|${done.row.due_at}`, true);
      try {
        // False: someone changed it since; it stays done.
        if (!(await undoCompleteReminder(client, done.undo))) throw new Error('moved on');
        refresh();
        return true;
      } catch {
        withHidden(`${id}|${done.row.due_at}`, false);
        failed();
        return false;
      }
    }
    withTick(id, null);
    try {
      await undoCompleteReminder(client, entry.done.undo);
      refresh();
      return true;
    } catch {
      withTick(id, entry);
      failed();
      return false;
    }
  };

  /** FR-007 Snooze: hidden at once. Returns when it comes back and the snooze it had, or null. */
  const snooze = async (row: PlacedReminder, option: ReminderSnoozeOption, source: ReminderActionSource, picked?: string): Promise<{ until: string; previous: string | null } | null> => {
    withHidden(row.id, true);
    try {
      const result = await snoozeReminder(client, row.id, option, tz, { picked });
      tracker.track('reminder_snoozed', { option, source });
      refresh();
      return result;
    } catch {
      withHidden(row.id, false);
      failed();
      return null;
    }
  };

  /** Undo of a snooze: the snooze it had before. */
  const unsnooze = async (id: string, previous: string | null): Promise<boolean> => {
    try {
      await setReminderSnooze(client, id, previous);
      withHidden(id, false);
      refresh();
      return true;
    } catch {
      failed();
      return false;
    }
  };

  /** FR-013: deleted at once (the whole series of a repeating one; the caller confirms that), with Undo. */
  const remove = async (row: PlacedReminder): Promise<boolean> => {
    withHidden(row.id, true);
    try {
      await deleteReminder(client, row.id);
      refresh();
      toast.show({
        text: r.deleted,
        onUndo: () =>
          deleteReminder(client, row.id, false).then(() => {
            withHidden(row.id, false);
            refresh();
          }),
      });
      return true;
    } catch {
      withHidden(row.id, false);
      failed();
      return false;
    }
  };

  const isTicked = useMemo(() => (id: string) => ticked.has(id), [ticked]);
  return { ticked, hidden, isTicked, tick, untick, snooze, unsnooze, remove, refresh };
}

export type ReminderActions = ReturnType<typeof useReminderActions>;
