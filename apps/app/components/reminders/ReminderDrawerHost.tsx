import { useEffect } from 'react';
import { router, type Href } from 'expo-router';
import { useQuery } from '@tanstack/react-query';
import { loadReminder, loadReminderHistory, setReminderNotes, type PlacedReminder } from '@cocon/data';
import type { ReminderActions, ReminderContext } from '../../lib/reminder-actions';
import { reminderHistoryKey } from '../../lib/reminders';
import { useOnline } from '../../lib/online';
import { ReminderDrawer } from './ReminderDrawer';

export interface OpenDrawer {
  row: PlacedReminder;
  source: 'home' | 'list' | 'calendar' | 'notification';
}

/** The drawer for one reminder, with its history and the screen's actions (Home and the Reminders screen). */
export function ReminderDrawerHost({ open, ctx, actions, onClose }: { open: OpenDrawer; ctx: ReminderContext; actions: ReminderActions; onClose: () => void }) {
  const online = useOnline();
  const { row, source } = open;
  const history = useQuery({ queryKey: reminderHistoryKey(ctx.familyId ?? '', row.id), queryFn: () => loadReminderHistory(ctx.client, row.id), enabled: row.late_hours >= 1 });
  useEffect(() => {
    ctx.tracker.track('reminder_drawer_opened', { source });
    // Once per opened reminder.
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, [row.id]);
  return (
    <ReminderDrawer
      reminder={row}
      members={ctx.members}
      history={history.data}
      today={ctx.today}
      tz={ctx.tz}
      use24h={ctx.use24h}
      weekStartsOn={ctx.weekStartsOn}
      readOnly={!online}
      tracker={ctx.tracker}
      // Spec 075: ticks save the notes; the lists refetch, so the drawer opens on them next time.
      noteChecklist={{
        save: (from, to) => setReminderNotes(ctx.client, row.id, from, to),
        reload: async () => (await loadReminder(ctx.client, row.id)).notes,
        onSaved: actions.refresh,
      }}
      onClose={onClose}
      onEdit={(focus) => {
        onClose();
        // Casts: the typed routes file (.expo/types) is generated by `expo start`.
        router.push(`/reminders/${row.id}/edit${focus ? `?focus=${focus}` : ''}` as Href);
      }}
      onDone={() => actions.tick(row, 'drawer')}
      onUndoDone={() => actions.untick(row.id)}
      onSnooze={(option, picked) => actions.snooze(row, option, 'drawer', picked)}
      onUndoSnooze={(previous) => actions.unsnooze(row.id, previous)}
      onDelete={() => actions.remove(row)}
    />
  );
}
