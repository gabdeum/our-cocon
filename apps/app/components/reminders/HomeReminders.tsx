import { useState } from 'react';
import { router, type Href } from 'expo-router';
import { useQuery } from '@tanstack/react-query';
import { hasOpenReminders, loadRemindersHome } from '@cocon/data';
import { useOnline } from '../../lib/online';
import { useReminderActions, useReminderContext } from '../../lib/reminder-actions';
import { FETCH_ON_OPEN, freshReminders, remindersExistKey, remindersHomeKey } from '../../lib/reminders';
import { ReminderDrawerHost, type OpenDrawer } from './ReminderDrawerHost';
import { RemindersCard } from './RemindersCard';

const TOP = 3;

/**
 * Home's Reminders card with its data (spec 057 FR-001): 056's `reminders_home`, live. Hidden when
 * nothing is due today or late (snoozed and later ones don't count), unless one was just ticked here.
 */
export function HomeReminders() {
  const ctx = useReminderContext();
  const online = useOnline();
  const { client, familyId } = ctx;
  const enabled = familyId !== null;
  const exists = useQuery({ queryKey: remindersExistKey(familyId ?? ''), queryFn: () => hasOpenReminders(client), enabled, ...FETCH_ON_OPEN });
  const home = useQuery({ queryKey: remindersHomeKey(familyId ?? '', ctx.tz), queryFn: () => loadRemindersHome(client, ctx.tz), enabled: enabled && exists.data === true, ...FETCH_ON_OPEN });
  const actions = useReminderActions(ctx);
  const [drawer, setDrawer] = useState<OpenDrawer | null>(null);
  // Not the copy saved on the device while online: a reload would show what has since been done.
  const hasAny = freshReminders(exists, online);
  const data = freshReminders(home, online);
  if (!hasAny || !data) return null;

  // Ticking pulls the next one up; the ticked ones stay, struck through, until Home is left.
  const open = data.rows.filter((x) => !actions.ticked.has(x.id) && !actions.hidden.has(x.id)).slice(0, TOP);
  const done = [...actions.ticked.values()].filter((t) => t.row.on_home).map((t) => ({ row: t.row, done: true }));
  if (!open.length && !done.length) return null;
  // Casts: the typed routes file (.expo/types) is generated by `expo start`.
  const go = (href: string) => router.push(href as Href);
  return (
    <>
      <RemindersCard
        rows={[...open.map((row) => ({ row, done: false })), ...done]}
        moreToday={data.moreToday}
        snoozed={data.snoozed}
        members={ctx.members}
        today={ctx.today}
        tz={ctx.tz}
        use24h={ctx.use24h}
        readOnly={!online}
        onToggle={(row, isDone) => void (isDone ? actions.untick(row.id) : actions.tick(row, 'home'))}
        onOpen={(row) => setDrawer({ row, source: 'home' })}
        onAdd={() => go('/reminders/new')}
        onSeeAll={() => go('/reminders')}
      />
      {drawer ? <ReminderDrawerHost open={drawer} ctx={ctx} actions={actions} onClose={() => setDrawer(null)} /> : null}
    </>
  );
}
