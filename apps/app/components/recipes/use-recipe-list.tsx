import { router, type Href } from 'expo-router';
import { useQuery } from '@tanstack/react-query';
import { MAX_TRACKED_STEPS } from '@cocon/schemas';
import { useCookActions } from '../cooking/use-cook-actions';
import { useCalendarDisplay } from '../../lib/calendar-prefs';
import { useOpenCooks } from '../../lib/cook-sessions';
import { useRecipePhotoUrls } from '../../lib/recipe-photo';
import { loadRecipeList, recipeListKey } from '../../lib/recipes';
import { filterScope, setRecipeFilters, setSheetSearch, useRecipeFilters } from '../../lib/recipe-filters';
import { useSession } from '../../lib/session';
import type { RecipeListProps } from './RecipeList';

// Cast: the typed routes file (.expo/types) is generated by `expo start` and may predate 008.
const newRecipe = '/recipes/new' as Href;

/**
 * Everything the Recipes list needs but where a recipe opens: the Recipes tab (specs 006, 007, 051)
 * and the list beside a recipe from 960 (spec 067) read the same live list, filters and cooks.
 * `enabled` false (a recipe on a phone) leaves the list unloaded.
 */
export function useRecipeList(enabled = true): Omit<RecipeListProps, 'onOpen'> {
  const { state, client, tracker } = useSession();
  const familyId = state.status === 'ready' ? state.family.id : null;
  const scope = filterScope(state);
  const filters = useRecipeFilters(scope);
  const list = useQuery({
    queryKey: recipeListKey(familyId ?? ''),
    queryFn: () => loadRecipeList(client),
    enabled: enabled && familyId !== null,
  });
  const photoUrls = useRecipePhotoUrls(client, familyId, list.data?.map((r) => r.photo_path) ?? []);
  // Spec 051 FR-003: recipes being cooked, live for the whole family.
  const cooks = useOpenCooks();
  const actions = useCookActions();
  const { use24h } = useCalendarDisplay().prefs;
  return {
    recipes: list.data,
    members: state.status === 'ready' ? state.members : [],
    tracker,
    failed: list.isError && !list.data,
    onRetry: () => void list.refetch(),
    onNew: () => router.push(newRecipe),
    filters,
    onFiltersChange: (next) => setRecipeFilters(scope, next),
    onOpenFilters: (query) => {
      setSheetSearch(scope, query);
      router.push('/recipes/filters');
    },
    photoUrls,
    cooks: cooks.data,
    use24h,
    onCookResume: (cook) => {
      tracker.track('cook_resumed', { from: 'list', step: Math.min(cook.current_step + 1, MAX_TRACKED_STEPS) });
      router.push(`/recipes/${cook.recipe_id}/cook` as Href);
    },
    onCookDone: (cook, name) => void actions.finish(cook, name),
    onCookCancel: (cook) => void actions.cancel(cook),
  };
}
