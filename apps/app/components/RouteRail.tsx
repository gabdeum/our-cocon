import { NavRail } from '@cocon/ui';
import type { Tracker } from '@cocon/schemas';
import { router, type Href } from 'expo-router';
import { useSafeAreaInsets } from 'react-native-safe-area-context';
import { RAIL_ITEMS, RAIL_PAGES, TABS, type RailKey } from '../lib/navigation';
import { strings } from '../strings';
import { AppTimerPill, useHasTimers } from './timers/AppTimerPill';

/** Where each tab's screen is, for a rail drawn outside the tab navigator. */
const tabHref = (route: string) => (route === 'index' ? '/' : `/${route}`) as Href;

const isPage = (key: RailKey): key is keyof typeof RAIL_PAGES => key in RAIL_PAGES;

/**
 * The rail on a screen pushed over the tabs (spec 067: a recipe beside the Recipes list, from 960;
 * Reminders and Timers, 2026-11-20). The same items and timer as AppTabBar's rail; a tab goes back to
 * its screen under the stack, without a slide. Reminders and Timers are pushed, or swapped for each other.
 */
export function RouteRail({ active, tracker, onOpenTimers }: { active: RailKey; tracker: Tracker; onOpenTimers: () => void }) {
  const insets = useSafeAreaInsets();
  const hasTimers = useHasTimers();
  const select = (key: RailKey) => {
    if (key === active) return;
    // Casts: the typed routes file (.expo/types) is generated by `expo start`.
    if (isPage(key)) {
      if (isPage(active)) router.replace(RAIL_PAGES[key] as Href);
      else router.push(RAIL_PAGES[key] as Href);
    } else {
      const tab = TABS.find((t) => t.key === key);
      if (!tab) return;
      // Back to the tabs already under the stack, in place: `navigate` would push a second copy of
      // them, sliding in.
      router.dismissTo(tabHref(tab.route));
    }
    tracker.track('tab_selected', { tab: key, nav: 'rail' });
  };
  return (
    <NavRail
      label={strings.tabBar.label}
      items={[...RAIL_ITEMS]}
      active={active}
      onSelect={select}
      insets={insets}
      timer={hasTimers ? <AppTimerPill vertical onOpen={onOpenTimers} tracker={tracker} /> : undefined}
    />
  );
}
