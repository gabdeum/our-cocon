import { useCallback, useState } from 'react';
import { router, useFocusEffect, type Href } from 'expo-router';
import { keepPreviousData, useQuery, useQueryClient } from '@tanstack/react-query';
import { todayIn } from '@cocon/calendar';
import { loadCalendarSettings, loadEvents, loadHomeHero } from '@cocon/data';
import { DebugFooter } from '../../components/DebugFooter';
import type { ActivityShow } from '../../components/activity/ActivitySection';
import { HomeScreen } from '../../components/home/HomeScreen';
import { activityKey, HOME_ENTRIES, loadActivity, undoActivity } from '../../lib/activity';
import { calendarSettingsKey, eventsKey } from '../../lib/calendar-header';
import { groceryListKey, loadGroceryList } from '../../lib/groceries';
import { cardWindow, homeHeroKey } from '../../lib/home';
import { useOnline } from '../../lib/online';
import { useRecipePhotoUrls } from '../../lib/recipe-photo';
import { loadRecipeList, recipeListKey } from '../../lib/recipes';
import { useSession } from '../../lib/session';
import { config } from '../../lib/tracker';
import { useNow } from '../../lib/use-now';

/**
 * Home (OC-Home, spec 028). Each block reads the same query as the screen it opens (Calendar,
 * Recipes, Groceries), so its numbers always match them and update live (SC-001).
 */
export default function HomeTab() {
  const { state, client, tracker } = useSession();
  const online = useOnline();
  const queryClient = useQueryClient();
  const familyId = state.status === 'ready' ? state.family.id : null;
  const enabled = familyId !== null;
  const settings = useQuery({ queryKey: calendarSettingsKey(familyId ?? ''), queryFn: () => loadCalendarSettings(client), enabled });
  const timeZone = settings.data?.homeTimeZone ?? Intl.DateTimeFormat().resolvedOptions().timeZone;
  const today = todayIn(timeZone);
  const now = useNow(timeZone);
  const { from, to } = cardWindow(today);
  const events = useQuery({ queryKey: eventsKey(familyId ?? '', from, to), queryFn: () => loadEvents(client, from, to), enabled });
  const recipes = useQuery({ queryKey: recipeListKey(familyId ?? ''), queryFn: () => loadRecipeList(client), enabled });
  const hero = useQuery({ queryKey: homeHeroKey(familyId ?? ''), queryFn: () => loadHomeHero(client), enabled });
  const groceries = useQuery({ queryKey: groceryListKey(familyId ?? ''), queryFn: () => loadGroceryList(client), enabled });
  // "All · AI only" isn't remembered: All each time Home comes back into view (FR-006).
  const [show, setShow] = useState<ActivityShow>('all');
  useFocusEffect(useCallback(() => setShow('all'), []));
  const filter = { ai: show === 'ai' };
  // The other filter's rows stay until these load, so AI only doesn't flash "No AI changes yet."
  const activity = useQuery({
    queryKey: [...activityKey(familyId ?? '', filter), 'home'],
    queryFn: () => loadActivity(client, HOME_ENTRIES, filter),
    enabled,
    placeholderData: keepPreviousData,
  });
  const photos = useRecipePhotoUrls(client, familyId, [hero.data?.photo_path]);

  if (state.status !== 'ready') return null;
  // Casts: the typed routes file (.expo/types) is generated by `expo start`.
  const go = (href: string) => router.push(href as Href);
  return (
    <HomeScreen
      me={state.me}
      members={state.members}
      today={today}
      now={now}
      slotTimes={settings.data?.slotTimes}
      events={events.data}
      hero={hero.data}
      heroPhotoUri={hero.data?.photo_path ? photos[hero.data.photo_path] : undefined}
      groceries={groceries.data}
      recipeCount={recipes.data?.length}
      activity={activity.data ?? []}
      activityShow={show}
      onActivityShow={setShow}
      readOnly={!online}
      tracker={tracker}
      onUndo={async (entry, skipChanged) => {
        const outcome = await undoActivity(client, entry.key, skipChanged);
        // What it put back is in other tables too (recipes, the grocery list, events).
        if (outcome.status === 'done' || outcome.status === 'expired') await queryClient.invalidateQueries();
        return outcome;
      }}
      footer={<DebugFooter config={config} />}
      navigate={{
        recipe: (id) => go(`/recipes/${id}`),
        newRecipe: () => go('/recipes/new'),
        groceries: () => router.navigate('/groceries'),
        recipes: () => router.navigate('/recipes'),
        family: () => go('/settings/family'),
        activity: (to) => go(`/activity?show=${to}`),
        event: (id, date) => go(`/calendar/${id}?date=${date}`),
        agenda: () => router.navigate('/calendar?view=agenda&from=home' as Href),
        calendar: () => router.navigate('/calendar?from=home' as Href),
        addEvent: (date) => go(`/calendar/new?date=${date}`),
      }}
    />
  );
}
