import { router, type Href } from 'expo-router';
import { useQuery } from '@tanstack/react-query';
import { todayIn } from '@cocon/calendar';
import { loadAssistants, loadCalendarSettings, loadEvents } from '@cocon/data';
import { DebugFooter } from '../../components/DebugFooter';
import { MenuScreen } from '../../components/menu/MenuScreen';
import { aiConnectionsKey } from '../../lib/assistants';
import { isBirthday } from '../../lib/calendar-day';
import { calendarSettingsKey, eventsKey } from '../../lib/calendar-header';
import { monthOccurrences } from '../../lib/calendar-month';
import { useCalendarDisplay } from '../../lib/calendar-prefs';
import { combineRows, groceryListKey, loadGroceryList, toBuyCount } from '../../lib/groceries';
import { cardWindow } from '../../lib/home';
import { loadRecipeList, recipeListKey } from '../../lib/recipes';
import { useDeletedItems } from '../../lib/recently-deleted';
import { useSession } from '../../lib/session';
import { useTimers } from '../../lib/timer-store';
import { config } from '../../lib/tracker';
import { strings } from '../../strings/en';

const m = strings.menu;

/**
 * /menu (spec 029, OC-Menu): Apps and Settings. Each tile reads the same query as the screen it
 * opens (and as Home), so its detail matches it and updates live.
 */
export default function MenuTab() {
  const { state, client, tracker } = useSession();
  const { prefs } = useCalendarDisplay();
  const familyId = state.status === 'ready' ? state.family.id : null;
  const enabled = familyId !== null;
  const userId = state.status === 'ready' ? state.userId : '';
  const myMemberId = state.status === 'ready' ? (state.members.find((x) => x.user_id === state.userId)?.id ?? state.me.id) : null;
  const settings = useQuery({ queryKey: calendarSettingsKey(familyId ?? ''), queryFn: () => loadCalendarSettings(client), enabled });
  const today = todayIn(settings.data?.homeTimeZone ?? Intl.DateTimeFormat().resolvedOptions().timeZone);
  const { from, to } = cardWindow(today);
  const events = useQuery({ queryKey: eventsKey(familyId ?? '', from, to), queryFn: () => loadEvents(client, from, to), enabled });
  const recipes = useQuery({ queryKey: recipeListKey(familyId ?? ''), queryFn: () => loadRecipeList(client), enabled });
  const groceries = useQuery({ queryKey: groceryListKey(familyId ?? ''), queryFn: () => loadGroceryList(client), enabled });
  const assistants = useQuery({ queryKey: aiConnectionsKey(userId), queryFn: () => loadAssistants(client), enabled: userId !== '' });
  // The same queries as Recently deleted, so the count and the list agree.
  const deleted = useDeletedItems(client, familyId, myMemberId);
  const { timers } = useTimers();

  if (state.status !== 'ready') return null;
  const todays = events.data
    ? monthOccurrences(events.data, today, today, myMemberId ?? '', new Set()).filter((o) => o.starts_on <= today && o.ends_on >= today && (prefs.show_birthdays || !isBirthday(o)))
    : undefined;
  const running = timers.filter((t) => t.state === 'running').length;
  const paused = timers.filter((t) => t.state === 'paused').length;
  return (
    <MenuScreen
      details={{
        calendar: todays && m.today(todays.length),
        recipes: recipes.data && m.recipeCount(recipes.data.length),
        groceries: groceries.data && m.toBuy(toBuyCount(combineRows(groceries.data))),
        timers: m.timersDetail(running, paused),
      }}
      memberNames={state.members.map((x) => x.display_name)}
      connected={assistants.data ? Object.keys(assistants.data.known).length + assistants.data.others.length : undefined}
      deleted={deleted.items?.length}
      tracker={tracker}
      // Casts: the typed routes file (.expo/types) is generated by `expo start`. Tabs switch, pages push.
      onNavigate={(href) => (href.startsWith('/settings/') || href === '/timers' ? router.push(href as Href) : router.navigate(href as Href))}
      footer={<DebugFooter config={config} />}
    />
  );
}
