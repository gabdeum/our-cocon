import { router, type Href } from 'expo-router';
import { useQuery, useQueryClient } from '@tanstack/react-query';
import { GroceryList } from '../../components/groceries/GroceryList';
import { useFamilySettings } from '../../lib/family-settings';
import {
  addItem,
  clearItems,
  editItem,
  groceryListKey,
  groceryPacksKey,
  loadGroceryList,
  loadPacks,
  moveToAisle,
  packKeys,
  restoreItems,
  savePackSize,
  setChecked,
  type GroceryItem,
} from '../../lib/groceries';
import { useRecipePhotoUrls } from '../../lib/recipe-photo';
import { useSession } from '../../lib/session';
import { optimisticWrite } from '../../lib/write';

// Cast: the typed routes file (.expo/types) is generated by `expo start`.
const recipePage = (id: string) => `/recipes/${id}` as Href;

/** /groceries (spec 020): the family's shared list, live. */
export default function GroceriesTab() {
  const { state, client, tracker } = useSession();
  const queryClient = useQueryClient();
  const familyId = state.status === 'ready' ? state.family.id : null;
  const key = groceryListKey(familyId ?? '');
  const list = useQuery({ queryKey: key, queryFn: () => loadGroceryList(client), enabled: familyId !== null });
  const items = list.data;
  const familySettings = useFamilySettings();
  const keys = packKeys(items ?? []);
  const packsKey = groceryPacksKey(familyId ?? '', keys);
  // Kept from the last list while a new item's packs load, so rows don't flicker back to "Need".
  const packs = useQuery({ queryKey: packsKey, queryFn: () => loadPacks(client, keys), enabled: familyId !== null && items !== undefined, placeholderData: (previous) => previous });
  const photoUrls = useRecipePhotoUrls(client, familyId, items?.map((i) => i.recipes?.photo_path) ?? []);

  // Every write refetches the list; live changes do the same on everyone else's device.
  const after = async <T,>(write: Promise<T>): Promise<T> => {
    try {
      return await write;
    } finally {
      void queryClient.invalidateQueries({ queryKey: key });
    }
  };

  return (
    <GroceryList
      items={items}
      failed={list.isError && !items}
      onRetry={() => void list.refetch()}
      me={state.status === 'ready' ? state.userId : ''}
      members={state.status === 'ready' ? state.members : []}
      tracker={tracker}
      photoUrls={photoUrls}
      onAdd={(text) => after(addItem(client, familyId ?? '', state.status === 'ready' ? state.userId : '', items ?? [], text))}
      onToggle={(item, checked) =>
        optimisticWrite<GroceryItem[]>(
          queryClient,
          key,
          (current) => current?.map((i) => (i.id === item.id ? { ...i, checked, checked_by: checked ? (state.status === 'ready' ? state.userId : null) : null, checked_at: checked ? new Date().toISOString() : null } : i)),
          () => setChecked(client, item.id, checked),
        )
      }
      onClear={(ids) => after(clearItems(client, ids))}
      onRestore={(ids) => after(restoreItems(client, ids))}
      onEdit={(item, text) => after(editItem(client, item, text))}
      onMove={(item, aisle) => after(moveToAisle(client, familyId ?? '', item, items ?? [], aisle))}
      onOpenRecipe={(id) => router.push(recipePage(id))}
      settings={familySettings.settings}
      packs={packs.data}
      onChangeSettings={familySettings.change}
      onSavePacks={async (item, text) => {
        try {
          return await savePackSize(client, familyId ?? '', item, text);
        } finally {
          void queryClient.invalidateQueries({ queryKey: ['family_ingredients', familyId ?? ''] });
        }
      }}
    />
  );
}
